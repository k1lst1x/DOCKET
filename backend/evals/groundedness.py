"""Step 8: groundedness evaluation of the chat agent against the real corpus.

Reads evals/questions.json:
  {"answerable": [{"question": "...", "expect": "text a relevant chunk contains"}, ...],
   "refusal": [{"question": "..."}, ...]}

Measures, per answerable question:
  retrieval hit   - hybrid search (top 12) returns a chunk containing `expect`
  answered        - the agent did not refuse
  citation valid  - every [n] marker maps to a citation, and re-running citation enforcement against
                    only the cited chunks removes nothing
  cited hit       - a cited chunk contains `expect`
and, per refusal question, whether the agent refused (target 100%).

Writes docs/eval-results.md. Run: python evals/groundedness.py
"""

import asyncio
import json
import re
import sys
from datetime import UTC, datetime
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from core import settings
from core.chat_agent import answer
from core.citations import enforce
from core.retrieval import fetch_chunks, hybrid_search

ROOT = Path(__file__).resolve().parent.parent
QUESTIONS_FILE = ROOT / "evals" / "questions.json"
RESULTS_FILE = ROOT / "docs" / "eval-results.md"
EVAL_USER = "eval-groundedness"


def _norm(text: str) -> str:
    return re.sub(r"\s+", " ", text).casefold()


def _contains(texts: list[str], expected: str) -> bool:
    needle = _norm(expected)
    return any(needle in _norm(text) for text in texts)


async def eval_answerable(item: dict) -> dict:
    question, expected = item["question"], item["expect"]
    retrieval_hit = _contains([e.text for e in hybrid_search(question)], expected)
    response = await answer(question, user_id=EVAL_USER)
    cited_texts = [e.cited_text() for e in fetch_chunks([c.chunk_id for c in response.citations])]
    refs = {int(n) for n in re.findall(r"\[(\d+)\]", response.answer)}
    markers_ok = bool(refs) and refs <= {c.ref for c in response.citations}
    citation_valid = not response.refused and markers_ok and not enforce(response.answer, cited_texts).removed
    return {
        "question": question,
        "retrieval_hit": retrieval_hit,
        "answered": not response.refused,
        "citation_valid": citation_valid,
        "cited_hit": _contains(cited_texts, expected),
        "answer": response.answer,
    }


async def eval_refusal(item: dict) -> dict:
    response = await answer(item["question"], user_id=EVAL_USER)
    return {"question": item["question"], "refused": response.refused, "answer": response.answer}


def _rate(rows: list[dict], key: str) -> str:
    hits = sum(row[key] for row in rows)
    return f"{hits}/{len(rows)} ({100 * hits / len(rows):.0f}%)" if rows else "n/a"


def _cell(text: str, limit: int = 160) -> str:
    text = re.sub(r"\s+", " ", text).replace("|", "\\|")
    return text if len(text) <= limit else text[: limit - 1] + "…"


def _mark(value: bool) -> str:
    return "yes" if value else "**no**"


def write_report(answerable: list[dict], refusal: list[dict]) -> None:
    lines = [
        "# DOCKET groundedness evaluation",
        "",
        f"Run {datetime.now(UTC):%Y-%m-%d %H:%M} UTC · model `{settings.BEDROCK_MODEL_ID}` · "
        f"embeddings `{settings.EMBED_MODEL_ID}` · generated by `evals/groundedness.py`",
        "",
        "## Summary",
        "",
        "| Metric | Result |",
        "|---|---|",
        f"| Retrieval hit rate (answerable) | {_rate(answerable, 'retrieval_hit')} |",
        f"| Answered (answerable) | {_rate(answerable, 'answered')} |",
        f"| Citation validity (answerable) | {_rate(answerable, 'citation_valid')} |",
        f"| Cited the expected evidence | {_rate(answerable, 'cited_hit')} |",
        f"| Correct refusals (target 100%) | {_rate(refusal, 'refused')} |",
        "",
        "## Answerable questions",
        "",
        "| # | Question | Retrieved | Answered | Citations valid | Cited expected | Answer |",
        "|---|---|---|---|---|---|---|",
    ]
    for i, row in enumerate(answerable, 1):
        lines.append(
            f"| {i} | {_cell(row['question'], 90)} | {_mark(row['retrieval_hit'])} "
            f"| {_mark(row['answered'])} | {_mark(row['citation_valid'])} | {_mark(row['cited_hit'])} "
            f"| {_cell(row['answer'])} |"
        )
    lines += ["", "## Refusal questions", "", "| # | Question | Refused | Answer |", "|---|---|---|---|"]
    for i, row in enumerate(refusal, 1):
        lines.append(
            f"| {i} | {_cell(row['question'], 90)} | {_mark(row['refused'])} | {_cell(row['answer'])} |"
        )
    RESULTS_FILE.parent.mkdir(parents=True, exist_ok=True)
    RESULTS_FILE.write_text("\n".join(lines) + "\n", encoding="utf-8")


async def main() -> None:
    questions = json.loads(QUESTIONS_FILE.read_text(encoding="utf-8"))
    answerable = []
    for item in questions["answerable"]:
        answerable.append(await eval_answerable(item))
        print(json.dumps({k: v for k, v in answerable[-1].items() if k != "answer"}, ensure_ascii=False))
    refusal = []
    for item in questions["refusal"]:
        refusal.append(await eval_refusal(item))
        print(
            json.dumps({"question": item["question"], "refused": refusal[-1]["refused"]}, ensure_ascii=False)
        )
    write_report(answerable, refusal)
    print(f"\nwrote {RESULTS_FILE}")
    print(
        f"retrieval {_rate(answerable, 'retrieval_hit')} · citations {_rate(answerable, 'citation_valid')} "
        f"· refusals {_rate(refusal, 'refused')}"
    )


if __name__ == "__main__":
    asyncio.run(main())
